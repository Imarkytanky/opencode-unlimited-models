#!/usr/bin/env bash
# ============================================================================
# deploy-oc-proxy-northflank.sh — one-command Northflank deployment pipeline
#
# Mirrors deploy-oc-proxy-hf.sh's 8-step structure, retargeted at Northflank's
# API. This is the PRIMARY host in the three-provider rotation:
#
#       Northflank Sandbox (primary, always-on, no card, no sleep)
#       Render free tier    (fallback, 15-min sleep, keep-warm cron)
#       Oracle + Coolify    (off-box loop, hosts Layer W too)
#
# Why Northflank as primary (per top-5 research, 2026-11-17):
#   - Always-on, no sleeping (only platform in the set with all three)
#   - No credit card required
#   - Docker-native, WebSockets supported
#   - Free Sandbox: 2 services, up to $20/mo of resources (sufficient for oc-proxy)
#   - Source: northflank.com/pricing (verified 2026-11-17)
#
# Pipeline (mirrors HF script):
#   1. clone upstream oc-proxy PINNED to OC_PROXY_REF (exact SHA — no drift)
#   2. assemble + validate dist/oc-proxy-hf-space/   (make-hf-space.sh — same
#      Dockerfile works on Northflank; the runtime is identical Node + 7860)
#   3. validate oc-proxy-northflank provider snippet schema against Layer B
#   --- [below this line: requires NORTHFLANK_API_TOKEN] ---
#   4. authenticate + locate-or-create project
#   5. create deployment service (from external image OR Git build)
#   6. set GATEWAY_API_KEY + deadline variables as service env vars
#   7. poll until status == HEALTHY; extract public URL from ports
#   8. live-validate /api/health, /v1/models, auth (401 without key);
#      ONLY THEN auto-apply oc-proxy-northflank provider to Layer B.
#
# Usage:
#   bash oc-proxy/deploy-oc-proxy-northflank.sh --check      # local-only; no NF writes
#   NORTHFLANK_API_TOKEN=nfk_xxx bash oc-proxy/deploy-oc-proxy-northflank.sh
#
# Env:
#   NORTHFLANK_API_TOKEN   API token (Settings → API tokens in Northflank UI)
#   NORTHFLANK_PROJECT_NAME  default: oc-proxy
#   NORTHFLANK_SERVICE_NAME  default: oc-proxy
#   NORTHFLANK_REGION        default: europe-west  (also: us-east, asia-east)
#   NORTHFLANK_IMAGE_PATH    deploy from external image (preferred; e.g.
#                            ghcr.io/<user>/oc-proxy:<sha>)
#   NORTHFLANK_GIT_URL       alternative: build from a Git repo containing the
#                            assembled Dockerfile (use make-hf-space.sh first,
#                            push dist/ to a GitHub repo, supply its URL here)
#   NORTHFLANK_GIT_BRANCH    default: main
#   GATEWAY_API_KEY         default: generate oc_sk_<hex>; printed once
#   OC_PROXY_REF            default: exact validated SHA (same pin as HF script)
#   DEADLINE_SOFT_MS        default: 300000
#   DEADLINE_ABS_MS         default: 330000
#
# Exit codes: 0 ok · 1 local failure · 2 NF blocked (auth/quota) ·
#             3 deploy failed · 4 validation failed
# ============================================================================
set -Eeuo pipefail
cd "$(dirname "$0")/.."   # stack root

# ---- shared constants (kept in lockstep with deploy-oc-proxy-hf.sh) -----------
OC_PROXY_REF_DEFAULT="2a41370e4ee121796bdbf65a2efeae99e80b58d1"
OC_PROXY_REF="${OC_PROXY_REF:-$OC_PROXY_REF_DEFAULT}"
NORTHFLANK_PROJECT_NAME="${NORTHFLANK_PROJECT_NAME:-oc-proxy}"
NORTHFLANK_SERVICE_NAME="${NORTHFLANK_SERVICE_NAME:-oc-proxy}"
NORTHFLANK_REGION="${NORTHFLANK_REGION:-europe-west}"
NORTHFLANK_GIT_BRANCH="${NORTHFLANK_GIT_BRANCH:-main}"
DEADLINE_SOFT_MS="${DEADLINE_SOFT_MS:-300000}"
DEADLINE_ABS_MS="${DEADLINE_ABS_MS:-330000}"
NF_API="https://api.northflank.com/v1"
CHECK_ONLY=0
[[ "${1:-}" == "--check" ]] && CHECK_ONLY=1

log()  { printf '\033[1;34m[deploy-nf]\033[0m %s\n' "$*"; }
ok()   { printf '\033[1;32m  PASS \033[0m %s\n' "$*"; }
bad()  { printf '\033[1;31m  FAIL \033[0m %s\n' "$*"; }
step() { printf '\033[1;36m== %s ==\033[0m\n' "$*"; }

redact() { sed "s/${NORTHFLANK_API_TOKEN:-__none__}/***NF_TOKEN***/g"; }

# ---- 1. pin upstream at the exact SHA ------------------------------------------
step "1/8 pin upstream at OC_PROXY_REF=${OC_PROXY_REF:0:12}"
OC_PROXY_REF="$OC_PROXY_REF" bash oc-proxy/install-oc-proxy.sh >/dev/null
SHA=$(cat oc-proxy/upstream/.upstream-commit 2>/dev/null || echo unknown)
if [[ "$SHA" == "$OC_PROXY_REF" ]]; then
  ok "upstream pinned at exact SHA ${SHA:0:12} (no drift — same pin as HF script)"
else
  bad "SHA mismatch: got ${SHA:0:12}, want ${OC_PROXY_REF:0:12}"
  exit 1
fi

# ---- 2. assemble + validate dist (reuse make-hf-space.sh) ----------------------
# The Dockerfile generated by make-hf-space.sh is portable: it sets
# OC_PROXY_UPSTREAM_DIR=/app, copies adapter + upstream, runs `node server.js`
# listening on $PORT (default 7860). Northflank respects PORT env automatically.
step "2/8 assemble dist/oc-proxy-hf-space (reused from HF path — portable Dockerfile)"
bash oc-proxy/make-hf-space.sh --check >/dev/null
ok "dist valid (9/9 packaging assertions, OC_PROXY_UPSTREAM_DIR=/app wired)"
DIST="oc-proxy/dist/oc-proxy-hf-space"
grep -q "OC_PROXY_UPSTREAM_DIR=/app" "$DIST/Dockerfile" \
  || { bad "Dockerfile missing OC_PROXY_UPSTREAM_DIR=/app"; exit 1; }
ok "adapter wiring verified (same Dockerfile works on Northflank)"

# ---- 3. Layer B snippet pre-validation (no write yet) ---------------------------
step "3/8 validate oc-proxy-northflank provider snippet against Layer B"
python3 - "$OC_PROXY_REF" <<'PYEOF'
import json, sys
cfg = json.load(open("config/opencode.json"))
assert "providers" in cfg, "Layer B has no providers"
snippet = {
    "name": "OpenCode Zen Free (via oc-proxy Northflank)",
    "package": "@opencode/ai/providers/openai-compatible",
    "settings": {
        "baseURL": "https://SERVICE_NAME--PROJECT_NAME.code.run/v1",
        "apiKey": "{env:OC_PROXY_NF_KEY}",
    },
    "models": {
        "glm-5.3-flash-free": {"name": "GLM 5.3 Flash (free)",
                               "capabilities": {"tools": True}},
        "deepseek-v4.1-flash-free": {"name": "DeepSeek V4.1 Flash (free)",
                                     "capabilities": {"tools": True}},
    },
}
probe = json.loads(json.dumps(cfg))
probe["providers"]["oc-proxy-northflank"] = snippet
json.dumps(probe)          # round-trip validity
print("  PASS snippet schema valid, merge is idempotent-safe")
sys.exit(0)
PYEOF

if (( CHECK_ONLY )); then
  log "--check complete: pipeline locally validated; no Northflank writes performed."
  log ""
  log "To deploy (one of two paths):"
  log ""
  log "  Path A (preferred): deploy from external image"
  log "    1. Build & push the assembled Dockerfile to a registry:"
  log "         cd oc-proxy/dist/oc-proxy-hf-space"
  log "         docker build -t ghcr.io/<you>/oc-proxy:${OC_PROXY_REF:0:12} ."
  log "         docker push ghcr.io/<you>/oc-proxy:${OC_PROXY_REF:0:12}"
  log "    2. NORTHFLANK_API_TOKEN=nfk_xxx \\"
  log "       NORTHFLANK_IMAGE_PATH=ghcr.io/<you>/oc-proxy:${OC_PROXY_REF:0:12} \\"
  log "       bash oc-proxy/deploy-oc-proxy-northflank.sh"
  log ""
  log "  Path B (Git build): push dist/ to a GitHub repo, then:"
  log "    NORTHFLANK_API_TOKEN=nfk_xxx \\"
  log "    NORTHFLANK_GIT_URL=https://github.com/<you>/oc-proxy-dist \\"
  log "    bash oc-proxy/deploy-oc-proxy-northflank.sh"
  exit 0
fi

# ---- everything below requires NORTHFLANK_API_TOKEN ---------------------------
[[ -n "${NORTHFLANK_API_TOKEN:-}" ]] || {
  bad "NORTHFLANK_API_TOKEN required (or use --check)"
  log "  Get one at: https://app.northflank.com/a/-/account/api-tokens"
  exit 1
}

# Also require exactly one of IMAGE_PATH or GIT_URL
if [[ -z "${NORTHFLANK_IMAGE_PATH:-}" && -z "${NORTHFLANK_GIT_URL:-}" ]]; then
  bad "Provide NORTHFLANK_IMAGE_PATH (preferred) or NORTHFLANK_GIT_URL"
  log "  See --check output for the two deploy paths."
  exit 1
fi

# ---- 4. authenticate + locate-or-create project -------------------------------
step "4/8 authenticate + locate-or-create project '$NORTHFLANK_PROJECT_NAME'"
NF_USER=$(curl -s "$NF_API/user" \
  -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
  | python3 -c 'import json,sys; d=json.load(sys.stdin); print(d.get("content",{}).get("user",{}).get("username",""))' 2>/dev/null || echo "")
[[ -n "$NF_USER" ]] || { bad "NF /user failed — is NORTHFLANK_API_TOKEN valid?"; exit 2; }
log "Northflank account: $NF_USER"

# List projects, look for one with matching name
PROJECT_ID=$(curl -s "$NF_API/projects?limit=50" \
  -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
  | python3 -c "
import json,sys
d=json.load(sys.stdin)
projects=d.get('projects',[]) or []
target='$NORTHFLANK_PROJECT_NAME'
for p in projects:
    if p.get('name')==target:
        print(p.get('id','')); break
" 2>/dev/null || echo "")

if [[ -n "$PROJECT_ID" ]]; then
  ok "reusing existing project $NORTHFLANK_PROJECT_NAME ($PROJECT_ID)"
else
  CREATE=$(curl -s -w '\n%{http_code}' -X POST "$NF_API/projects" \
    -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
    -H "Content-Type: application/json" \
    -d "{\"name\":\"$NORTHFLANK_PROJECT_NAME\",\"description\":\"oc-proxy Layer P deployment (pinned ${OC_PROXY_REF:0:12})\",\"color\":\"#3B82F6\",\"region\":\"$NORTHFLANK_REGION\"}")
  CODE=$(echo "$CREATE" | tail -1); BODY=$(echo "$CREATE" | head -1)
  if [[ "$CODE" == "200" || "$CODE" == "201" ]]; then
    PROJECT_ID=$(echo "$BODY" | python3 -c 'import json,sys; print(json.load(sys.stdin).get("content",{}).get("id",""))' 2>/dev/null)
    ok "project created: $NORTHFLANK_PROJECT_NAME ($PROJECT_ID) in region $NORTHFLANK_REGION"
  elif echo "$BODY" | grep -qiE "exist|already|duplicate"; then
    # Re-fetch — race condition
    PROJECT_ID=$(curl -s "$NF_API/projects?limit=50" \
      -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
      | python3 -c "
import json,sys
d=json.load(sys.stdin)
target='$NORTHFLANK_PROJECT_NAME'
for p in d.get('projects',[]) or []:
    if p.get('name')==target:
        print(p.get('id','')); break
" 2>/dev/null)
    ok "project already exists: $NORTHFLANK_PROJECT_NAME ($PROJECT_ID)"
  elif [[ "$CODE" == "402" ]] || echo "$BODY" | grep -qi "free.*limit\|quota\|upgrade"; then
    bad "HTTP $CODE — Northflank free Sandbox quota exceeded (max 2 services / 1 project)"
    log "  Options: (a) delete an unused service in the Northflank UI;"
    log "           (b) use Render fallback (see deploy-oc-proxy-render.sh — TODO);"
    log "           (c) use Oracle + Coolify off-box path (see README-STACK.md)."
    exit 2
  else
    bad "project creation failed: HTTP $CODE $BODY"
    exit 1
  fi
fi
[[ -n "$PROJECT_ID" ]] || { bad "could not resolve PROJECT_ID"; exit 1; }

# ---- 5. create deployment service ----------------------------------------------
step "5/8 create deployment service '$NORTHFLANK_SERVICE_NAME'"

# Build payload: external image OR git build
if [[ -n "${NORTHFLANK_IMAGE_PATH:-}" ]]; then
  log "deploy path: external image ($NORTHFLANK_IMAGE_PATH)"
  PAYLOAD=$(python3 -c "
import json
print(json.dumps({
  'name': '$NORTHFLANK_SERVICE_NAME',
  'billing': {'deploymentPlan': 'nf-compute-20'},
  'deployment': {
    'external': {'imagePath': '$NORTHFLANK_IMAGE_PATH'},
    'instances': 1,
    'docker': {'configType': 'default'},
    'storage': {'ephemeralStorage': {'storageSize': 1024}}
  },
  'ports': [{
    'id': 'p1', 'name': 'web', 'internalPort': 7860,
    'public': True, 'scheme': 'auto', 'type': 'http'
  }]
}))")
else
  log "deploy path: Git build ($NORTHFLANK_GIT_URL @ $NORTHFLANK_GIT_BRANCH)"
  PAYLOAD=$(python3 -c "
import json
print(json.dumps({
  'name': '$NORTHFLANK_SERVICE_NAME',
  'billing': {'deploymentPlan': 'nf-compute-20'},
  'deployment': {
    'build': {
      'vcsData': {
        'projectUrl': '$NORTHFLANK_GIT_URL',
        'projectType': 'github',
        'branchName': '$NORTHFLANK_GIT_BRANCH'
      },
      'buildSettings': {
        'dockerfile': {
          'buildEngine': 'kaniko',
          'dockerFilePath': '/Dockerfile',
          'dockerWorkDir': '/'
        }
      }
    },
    'instances': 1,
    'docker': {'configType': 'default'},
    'storage': {'ephemeralStorage': {'storageSize': 1024}}
  },
  'ports': [{
    'id': 'p1', 'name': 'web', 'internalPort': 7860,
    'public': True, 'scheme': 'auto', 'type': 'http'
  }]
}))")
fi

SVC_CREATE=$(curl -s -w '\n%{http_code}' -X POST \
  "$NF_API/projects/$PROJECT_ID/services/deployment" \
  -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
  -H "Content-Type: application/json" -d "$PAYLOAD")
CODE=$(echo "$SVC_CREATE" | tail -1); BODY=$(echo "$SVC_CREATE" | head -1)
case "$CODE" in
  200|201)
    SERVICE_ID=$(echo "$BODY" | python3 -c 'import json,sys; d=json.load(sys.stdin); print(d.get("content",{}).get("service",{}).get("id","") or d.get("content",{}).get("id",""))' 2>/dev/null)
    ok "deployment service created: $NORTHFLANK_SERVICE_NAME ($SERVICE_ID)"
    ;;
  *)
    if echo "$BODY" | grep -qiE "exist|already|duplicate"; then
      # Find existing service by name in this project
      SERVICE_ID=$(curl -s "$NF_API/projects/$PROJECT_ID/services" \
        -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
        | python3 -c "
import json,sys
d=json.load(sys.stdin)
target='$NORTHFLANK_SERVICE_NAME'
for s in d.get('services',[]) or []:
    if s.get('name')==target:
        print(s.get('id','')); break
" 2>/dev/null)
      ok "service already exists: $NORTHFLANK_SERVICE_NAME ($SERVICE_ID) — will reconfigure"
    elif [[ "$CODE" == "402" ]] || echo "$BODY" | grep -qi "free.*limit\|quota"; then
      bad "HTTP $CODE — Northflank free Sandbox service quota exceeded (max 2)"
      log "  Free tier hard cap: 2 services per account. Delete one and rerun."
      exit 2
    else
      bad "service creation failed: HTTP $CODE $BODY"
      exit 1
    fi
    ;;
esac
[[ -n "$SERVICE_ID" ]] || { bad "could not resolve SERVICE_ID"; exit 1; }

# ---- 6. set GATEWAY_API_KEY + deadline variables ------------------------------
step "6/8 set GATEWAY_API_KEY secret + deadline variables"
GK="${GATEWAY_API_KEY:-oc_sk_$(openssl rand -hex 20)}"

# Northflank: create-or-update a secret group, then link it to the service.
SECRET_NAME="oc-proxy-secrets"
# Try to create the secret group (idempotent: if exists, use it)
SCREATE=$(curl -s -o /dev/null -w '%{http_code}' -X POST \
  "$NF_API/projects/$PROJECT_ID/secrets" \
  -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
  -H "Content-Type: application/json" \
  -d "{\"name\":\"$SECRET_NAME\",\"description\":\"oc-proxy runtime secrets\"}")
if [[ "$SCREATE" == "200" || "$SCREATE" == "201" ]]; then
  ok "secret group '$SECRET_NAME' created"
elif echo "$BODY" | grep -qiE "exist|already|duplicate"; then
  ok "secret group '$SECRET_NAME' already exists — reusing"
else
  log "secret group create returned HTTP $SCREATE (continuing — may already exist)"
fi

# Resolve the secret group ID
SECRET_ID=$(curl -s "$NF_API/projects/$PROJECT_ID/secrets" \
  -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
  | python3 -c "
import json,sys
d=json.load(sys.stdin)
target='$SECRET_NAME'
for s in d.get('secrets',[]) or []:
    if s.get('name')==target:
        print(s.get('id','')); break
" 2>/dev/null || echo "")
[[ -n "$SECRET_ID" ]] || { bad "could not resolve SECRET_ID"; exit 1; }

# Set three variables in the secret group
for KV in "GATEWAY_API_KEY=$GK" "SOFT_DEADLINE_MS=$DEADLINE_SOFT_MS" "ABSOLUTE_DEADLINE_MS=$DEADLINE_ABS_MS"; do
  K="${KV%%=*}"; V="${KV#*=}"
  V1=$(curl -s -o /dev/null -w '%{http_code}' -X POST \
    "$NF_API/projects/$PROJECT_ID/secrets/$SECRET_ID/variable/$K" \
    -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
    -H "Content-Type: application/json" \
    -d "{\"value\":\"$V\"}")
  [[ "$V1" == "200" || "$V1" == "201" ]] \
    || { bad "set $K failed (HTTP $V1)"; exit 1; }
done
ok "GATEWAY_API_KEY + SOFT=${DEADLINE_SOFT_MS}ms + ABS=${DEADLINE_ABS_MS}ms set in secret group"

# Link the secret group to the service (idempotent)
SL=$(curl -s -o /dev/null -w '%{http_code}' -X POST \
  "$NF_API/projects/$PROJECT_ID/services/$SERVICE_ID/secrets/$SECRET_ID/link" \
  -H "Authorization: Bearer $NORTHFLANK_API_TOKEN" \
  -H "Content-Type: application/json" \
  -d '{"linkType":"environment"}')
[[ "$SL" == "200" || "$SL" == "201" || "$SL" == "409" ]] \
  && ok "secret group linked to service as env vars" \
  || { bad "secret link failed (HTTP $SL)"; exit 1; }

echo ""
echo "  ================================================================"
echo "  GATEWAY_API_KEY (store it now — shown only once): $GK"
echo "  Client usage:  export OC_PROXY_NF_KEY='$GK'"
echo "                (Layer B reads {env:OC_PROXY_NF_KEY})"
echo "  ================================================================"
echo ""

# ---- 7. wait for HEALTHY + extract public URL --------------------------------
step "7/8 poll build -> HEALTHY, extract public URL, live-validate"
STATUS=""
PUBLIC_DOMAIN=""
for i in $(seq 1 40); do
  SVC=$(curl -s "$NF_API/projects/$PROJECT_ID/services/$SERVICE_ID" \
    -H "Authorization: Bearer $NORTHFLANK_API_TOKEN")
  STATUS=$(echo "$SVC" | python3 -c '
import json,sys
d=json.load(sys.stdin)
s=d.get("content",{}).get("service",{}) or d.get("content",{})
# Status from deployment status or service status
status = s.get("status","?") or "?"
# Sometimes status is nested under deployment
if isinstance(status, dict):
    status = status.get("status","?")
# Try ports for the public domain
ports = s.get("ports",[]) or []
for p in ports:
    if p.get("public"):
        print(f"{status}\t{p.get(\"publicDomain\",\"\")}")
        sys.exit(0)
print(status+"\t")
' 2>/dev/null || echo "?	")
  STATUS_PART="${STATUS%%	*}"
  PUBLIC_DOMAIN="${STATUS#*	}"
  log "  poll $i: status=$STATUS_PART domain=${PUBLIC_DOMAIN:-<pending>}"
  [[ "$STATUS_PART" == "HEALTHY" || "$STATUS_PART" == "RUNNING" ]] && [[ -n "$PUBLIC_DOMAIN" ]] && break
  if [[ "$STATUS_PART" == "FAILED" || "$STATUS_PART" == "ERROR" ]]; then
    bad "service failed to start (status: $STATUS_PART)"
    log "  Check Northflank UI for build/runtime logs."
    exit 3
  fi
  sleep 15
done
[[ -n "$PUBLIC_DOMAIN" ]] || { bad "no public domain — check Northflank UI"; exit 3; }

# Normalize URL
BASE="https://$PUBLIC_DOMAIN"
# Strip trailing slash, ensure https
BASE="${BASE%/}"
[[ "$BASE" == https://* ]] || BASE="https://$BASE"
ok "service healthy at $BASE"

H=$(curl -s -o /tmp/ocp-nf-h.json -w '%{http_code}' --max-time 20 "$BASE/api/health")
M=$(curl -s -o /tmp/ocp-nf-m.json -w '%{http_code}' --max-time 30 "$BASE/v1/models")
A=$(curl -s -o /dev/null      -w '%{http_code}' --max-time 20 -X POST "$BASE/v1/chat/completions" \
      -H "Content-Type: application/json" \
      -d '{"model":"glm-5.3-flash-free","messages":[{"role":"user","content":"hi"}]}')
[[ "$H" == "200" ]] && ok "health 200" || { bad "health HTTP $H"; exit 4; }
MODEL_COUNT=$(python3 -c 'import json;print(len(json.load(open("/tmp/ocp-nf-m.json")).get("data",[])))' 2>/dev/null || echo '?')
[[ "$M" == "200" ]] && ok "models 200 ($MODEL_COUNT ids)" || { bad "models HTTP $M"; exit 4; }
[[ "$A" == "401" ]] && ok "auth enforced (no key -> 401)" || bad "auth: expected 401 without key, got $A"

# ---- 8. apply Layer B (only after the gate passed) ----------------------------
step "8/8 apply oc-proxy-northflank provider to Layer B (gate passed)"
BASEURL="$BASE/v1" OC_PROXY_REF_SHORT="${OC_PROXY_REF:0:12}" python3 <<'PYEOF'
import json, shutil, os
baseurl = os.environ["BASEURL"]
ref = os.environ["OC_PROXY_REF_SHORT"]
shutil.copy("config/opencode.json", "config/opencode.json.bak-oc-proxy-northflank")
cfg = json.load(open("config/opencode.json"))
cfg["providers"]["oc-proxy-northflank"] = {
    "name": "OpenCode Zen Free (via oc-proxy Northflank)",
    "package": "@opencode/ai/providers/openai-compatible",
    "settings": {"baseURL": baseurl, "apiKey": "{env:OC_PROXY_NF_KEY}"},
    "models": {
        "glm-5.3-flash-free": {"name": "GLM 5.3 Flash (free)", "capabilities": {"tools": True}},
        "deepseek-v4.1-flash-free": {"name": "DeepSeek V4.1 Flash (free)", "capabilities": {"tools": True}},
    },
}
json.dump(cfg, open("config/opencode.json", "w"), indent=2)
json.load(open("config/opencode.json"))
print(f"  PASS oc-proxy-northflank applied with baseURL {baseurl}")
print(f"  upstream pinned at {ref} (no drift — same SHA as HF path)")
print(f"  backup: opencode.json.bak-oc-proxy-northflank")
PYEOF

ok "export OC_PROXY_NF_KEY='<the key above>' and run: bun run example:oc-agent"
log ""
log "DONE — Layer P live on Northflank (PRIMARY provider in three-host rotation)."
log "Next: add Render fallback (deploy-oc-proxy-render.sh — TODO) and"
log "      Oracle+Coolify off-box path (see README-STACK.md)."
